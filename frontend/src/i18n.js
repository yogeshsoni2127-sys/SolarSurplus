const KEY = 'solarsurplus_lang';
const listeners = new Set();

function readLang() {
  try {
    return localStorage.getItem(KEY) === 'hi' ? 'hi' : 'en';
  } catch (e) {
    return 'en';
  }
}

function setLangStore(lang) {
  try {
    localStorage.setItem(KEY, lang);
  } catch (e) {}
  listeners.forEach((fn) => fn(lang));
}

/** Template fill: f(t('x'), {v: 3}) replaces {v} tokens. */
export function f(template, vals = {}) {
  return template.replace(/\{(\w+)\}/g, (_, k) => (k in vals ? vals[k] : `{${k}}`));
}

export function toggleLanguage() {
  setLangStore(readLang() === 'hi' ? 'en' : 'hi');
}

export function useI18n() {
  const [lang, setLang] = useState(readLang);
  useEffect(() => {
    const fn = (l) => setLang(l);
    listeners.add(fn);
    return () => listeners.delete(fn);
  }, []);
  const t = (key) => (DICT[lang] && DICT[lang][key]) || DICT.en[key] || key;
  return { lang, t };
}